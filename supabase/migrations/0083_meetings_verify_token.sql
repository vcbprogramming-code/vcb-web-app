-- gen_random_uuid() เป็นฟังก์ชัน volatile — Postgres จึงเขียนตารางใหม่และแจก
-- ค่าที่ต่างกันให้ทุกแถวที่มีอยู่ ไม่ใช่ค่าเดียวกันทั้งตาราง (ถ้าเป็น default
-- แบบคงที่จะได้ค่าเดียวกันหมด ซึ่งเท่ากับไม่มีกุญแจเลย)
alter table mtg_meetings
  add column if not exists verify_token uuid not null default gen_random_uuid();

-- กุญแจซ้ำกันไม่ได้ ไม่อย่างนั้นสองฉบับก็ตรวจสอบได้ด้วยกระดาษใบเดียวกัน
create unique index if not exists mtg_meetings_verify_token_idx
  on mtg_meetings (verify_token);

comment on column mtg_meetings.verify_token is
  'กุญแจเดาไม่ได้สำหรับ QR บนเอกสารที่พิมพ์ → หน้าตรวจสอบสาธารณะ /mtg/:token';
