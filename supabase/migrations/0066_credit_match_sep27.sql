-- วงเงินสินเชื่อ — อัตราดอกเบี้ยเป็นข้อความอิสระ (เทียบระบบจริง 2026-09-27)
--
-- ของเราเก็บอัตราดอกเบี้ยเป็นตัวเลขอย่างเดียว แต่หนังสือวงเงินของธนาคารเขียน
-- เงื่อนไขไว้เป็นประโยค — "MLR ต่อปี" หรือ "1.25 % ต่อปีเรียกเก็บทุก 3 เดือน"
-- ช่องตัวเลขรับประโยคแบบนั้นไม่ได้ คนกรอกจึงต้องปัดเศษความจริงทิ้งไปหนึ่งชั้น
--
-- ระบบจริงของลูกค้าเก็บช่องนี้เป็นข้อความ แล้วตอนคำนวณดอกเบี้ยเกินกำหนดค่อย
-- ดึงตัวเลขออกมาด้วย regex — ไม่เจอตัวเลขก็ไม่คำนวณ แต่ไม่พัง (facRatePct ใน
-- index.html) เราทำแบบเดียวกัน
--
-- คอลัมน์ตัวเลขเดิม (interest_rate) ยังอยู่ ไม่ถูกแตะ: รายงานและโค้ดรุ่นก่อน
-- ยังอ่านได้เหมือนเดิม คอลัมน์ใหม่เป็น null ได้ทั้งหมด จึงเป็นการ "เพิ่ม" ล้วน
-- ═══════════════════════════════════════════════════════════════════════════

alter table facilities add column if not exists interest_note text;

-- เติมข้อความจากตัวเลขที่มีอยู่ ให้ช่องใหม่อ่านได้ทันทีตั้งแต่วันแรก — ทำครั้ง
-- เดียวเฉพาะแถวที่ยังว่าง การรัน migration ซ้ำจึงไม่เขียนทับสิ่งที่คนแก้ไว้แล้ว
update facilities
   set interest_note = trim(to_char(interest_rate, 'FM999999990.99')) || ' % ต่อปี'
 where interest_note is null and interest_rate is not null;

comment on column facilities.interest_note is
  'อัตราดอกเบี้ยตามหนังสือธนาคาร เป็นข้อความอิสระ เช่น "MLR ต่อปี" · การคำนวณดอกเบี้ยเกินกำหนดดึงตัวเลขจากข้อความนี้ด้วย regex ไม่เจอก็ไม่คำนวณ (ดู ratePct ใน services/credit.js)';
