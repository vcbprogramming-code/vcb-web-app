-- ทะเบียนงานและหมวดต้นทุนตามระบบจริงของลูกค้า
--
-- ระบบ HR Work Log ที่พนักงานใช้อยู่ทุกวัน (Google Apps Script) เก็บงานหนึ่งวัน
-- เป็น "รหัสงาน / รหัสหมวดต้นทุน" เช่น "A-1 / 5" โดยรหัสงานแต่ละตัวกำหนดไว้ว่า
-- ใช้กับหมวดต้นทุนใดได้บ้าง (MasterIndex.allowed_cost) — ตารางของเราไม่เคยมี
-- คอลัมน์นั้น ขั้นที่สองของตัวเลือกจึงแสดงหมวดต้นทุนทั้งหมดโดยไม่กรอง
--
-- คอลัมน์ทั้งสามนี้ตรงกับหัวตาราง MasterIndex ของระบบจริง:
--   ['id','code','name','desc','category','sites','mapping','fixed_cost','allowed_cost']
-- ═══════════════════════════════════════════════════════════════════════════

alter table work_types add column if not exists name_en      text;
-- รายการรหัสหมวดต้นทุนที่รหัสงานนี้ใช้ได้ คั่นด้วยจุลภาค เช่น '5,7,8,9,15,17,19'
-- ว่าง = ไม่มีต้นทุน (กลุ่ม Z ไม่ปฏิบัติงาน) ซึ่งตกไปใช้ fixed_cost ตามเดิม
alter table work_types add column if not exists allowed_cost text;
-- ไซต์งานที่ใช้รหัสนี้ได้ ว่าง = ทุกไซต์ (ระบบจริงเว้นว่างไว้ทั้งหมดในตอนนี้)
alter table work_types add column if not exists sites        text;

comment on column work_types.allowed_cost is
  'รหัสหมวดต้นทุนที่ใช้กับรหัสงานนี้ได้ คั่นด้วยจุลภาค — 1 รหัส = เลือกให้อัตโนมัติ, หลายรหัส = ให้ผู้ใช้เลือกต่อ, ว่าง = ไม่มีต้นทุน';
