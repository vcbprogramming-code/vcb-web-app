-- วงเงินสินเชื่อ — กุญแจอ้างกลับไปยังรายการต้นทางของระบบเดิม
--
-- การนำเข้าข้อมูลจริง (scripts/import-live-credit.mjs) ต้องรันซ้ำได้โดยไม่เกิด
-- แถวซ้ำ วงเงินมีกุญแจธรรมชาติอยู่แล้ว (โครงการ × เลขประเภทวงเงิน) แต่รายการ
-- ใช้วงเงินไม่มี — เลขที่เอกสาร (ref) ซ้ำกันได้ และยอด/วันที่ก็แก้ได้ทีหลัง
-- จึงต้องเก็บ "id ของแถวต้นทาง" (SEED-1, TXN-1779642997764, …) ไว้ตรง ๆ
--
-- คอลัมน์นี้เป็น null ได้ทั้งหมดและไม่มีโค้ดเดิมอ่านหรือเขียน รายการที่คนกรอก
-- ผ่านหน้าจอจึงเป็น null เหมือนเดิม ส่วนรายการที่มาจากการนำเข้ามีค่า — ทำให้
-- การนำเข้ารอบถัดไปรู้ว่าแถวไหนเป็นของตัวเอง และล้างได้เฉพาะของตัวเอง
-- ═══════════════════════════════════════════════════════════════════════════

alter table credit_ledger add column if not exists source_id text;

-- การนำเข้าอ่านคอลัมน์นี้ทีละแถวเพื่อตัดสินว่าจะ insert หรือ update
create index if not exists credit_ledger_source_id_idx
  on credit_ledger (source_id) where source_id is not null;

comment on column credit_ledger.source_id is
  'id ของแถวต้นทางในระบบเดิม (Transactions ของ Apps Script) · null = รายการที่กรอกในระบบเรา · ใช้เป็นกุญแจกันข้อมูลซ้ำใน scripts/import-live-credit.mjs';
