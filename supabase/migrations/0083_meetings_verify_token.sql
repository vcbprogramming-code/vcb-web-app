-- รายงานการประชุม — กุญแจตรวจสอบความแท้สำหรับ QR บนเอกสารที่พิมพ์ (2026-09-27)
--
-- ของลูกค้าประทับ QR ไว้ในกรอบขอบขวาบนของหน้ากระดาษทุกหน้า (buildQrPageCss_ ใน
-- JavaScript.html) แล้วให้ QR นั้นชี้กลับไปที่ลิงก์ ?meeting=<id> ของแอปตัวเอง
-- ซึ่งใช้ได้กับ "คนใน" เท่านั้น เพราะแอปของเขาอยู่หลังการลงชื่อเข้าใช้ Google
--
-- ของเราเลือกกุญแจเดาไม่ได้ต่อหนึ่งฉบับ แล้วเปิดหน้าตรวจสอบสาธารณะที่ /mtg/:token
-- ด้วยเหตุผลสามข้อ (เขียนไว้เต็มในหัวไฟล์ meetingVerify.routes.js):
--   1. กระดาษที่พิมพ์ออกไปหลุดออกนอกองค์กรได้ ผู้รับที่ไม่มีบัญชีต้องพิสูจน์ได้
--      ว่าเอกสารในมือออกจากระบบเราจริง ไม่ใช่กดลิงก์แล้วเจอหน้าให้ล็อกอิน
--   2. id ของฉบับไม่ใช่ความลับ — มันอยู่ในลิงก์ที่แจกกันภายใน (?meeting=<id>)
--      และอยู่ในแถบที่อยู่ของทุกคนที่เปิดอ่าน ถ้าเส้นทางสาธารณะรับ id ตรง ๆ
--      คนที่เคยเห็นลิงก์ภายในก็เปิดหน้าสาธารณะได้ทันที กุญแจแยกจึงจำเป็น
--   3. E-Memo ใช้รูปแบบนี้อยู่แล้ว (documents.verify_token → /verify/:token)
--      รูปแบบเดียวกันแปลว่าไม่มีกลไกความปลอดภัยชนิดใหม่ให้ต้องรีวิวเพิ่ม
--
-- หน้าสาธารณะแสดงเฉพาะหลักฐานว่าเอกสารแท้ (ชื่อเรื่อง โครงการ วันประชุม ปรับแก้
-- ครั้งสุดท้ายเมื่อไร กี่เวอร์ชัน) ไม่เคยส่งเนื้อหาบันทึกออกไป
--
-- เพิ่มคอลัมน์อย่างเดียว มีค่าตั้งต้น จึงเข้ากันได้กับโค้ดรุ่นก่อนทุกบรรทัด
-- (เซิร์ฟเวอร์ dev รัน migration กับฐานข้อมูลจริง)
